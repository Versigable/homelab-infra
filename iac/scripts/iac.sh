#!/usr/bin/env bash
# Runs the iac/ toolchain from the control node (for the pilot: WSL Debian on
# MetaVersig's workstation, with terraform and an Ansible venv).
#
#   iac.sh tf <terraform args>    terraform in iac/terraform/$IAC_SITE (default xmansion)
#   iac.sh inventory              write the site's guest inventory from Terraform's output
#                                 (ansible/inventory/guests.yml for xmansion, guests-<site>.yml
#                                 for the others; Ansible reads them all)
#   iac.sh play <playbook> [args] ansible-playbook iac/ansible/playbooks/<playbook>
#   iac.sh bootstrap <guest>      first contact with a new guest (as root, once)
#
# Secrets are read from files and only ever exported into the tool's environment:
#   $IAC_CONF/pve-token    iac@pve!infra=<secret>                      (0600)
#   $GITLAB_TOKEN_FILE     env file with GITLAB_TOKEN_IACSTATE (Maintainer on the
#                          state project) and any GITLAB_RUNNER_TOKEN_<GUEST>
# Non-secret settings come from $IAC_CONF/state.env: GITLAB_URL and IAC_STATE_PROJECT
# (the numeric id of the GitLab project that holds Terraform state).
set -euo pipefail

IAC_DIR=$(cd "$(dirname "$0")/.." && pwd)
IAC_CONF=${IAC_CONF:-$HOME/.config/homelab-iac}
IAC_SITE=${IAC_SITE:-xmansion}
IAC_VENV=${IAC_VENV:-$HOME/.venvs/lab}
GITLAB_TOKEN_FILE=${GITLAB_TOKEN_FILE:-}
export PATH="$HOME/.local/bin:$IAC_VENV/bin:$PATH"

die() { echo "iac.sh: $*" >&2; exit 1; }

token_from_file() {
  [[ -n "$GITLAB_TOKEN_FILE" && -r "$GITLAB_TOKEN_FILE" ]] || die "set GITLAB_TOKEN_FILE to a readable env file"
  sed -n "s/^$1=//p" "$GITLAB_TOKEN_FILE" | tr -d '"\r'
}

tf_env() {
  [[ -r "$IAC_CONF/pve-token" ]] || die "missing $IAC_CONF/pve-token"
  [[ -r "$IAC_CONF/state.env" ]] || die "missing $IAC_CONF/state.env"
  # shellcheck disable=SC1091
  . "$IAC_CONF/state.env"
  : "${GITLAB_URL:?state.env must set GITLAB_URL}" "${IAC_STATE_PROJECT:?state.env must set IAC_STATE_PROJECT}"

  PROXMOX_VE_API_TOKEN=$(cat "$IAC_CONF/pve-token")
  export PROXMOX_VE_API_TOKEN

  local state_token user address
  state_token=$(token_from_file GITLAB_TOKEN_IACSTATE)
  [[ -n "$state_token" ]] || die "GITLAB_TOKEN_IACSTATE not found in $GITLAB_TOKEN_FILE"
  user=$(curl -fsS -H "PRIVATE-TOKEN: $state_token" "$GITLAB_URL/api/v4/user" \
    | python3 -c 'import sys,json; print(json.load(sys.stdin)["username"])')
  address="$GITLAB_URL/api/v4/projects/$IAC_STATE_PROJECT/terraform/state/$IAC_SITE"

  export TF_HTTP_ADDRESS="$address"
  export TF_HTTP_LOCK_ADDRESS="$address/lock"
  export TF_HTTP_UNLOCK_ADDRESS="$address/lock"
  export TF_HTTP_LOCK_METHOD=POST
  export TF_HTTP_UNLOCK_METHOD=DELETE
  export TF_HTTP_RETRY_WAIT_MIN=5
  export TF_HTTP_USERNAME="$user"
  export TF_HTTP_PASSWORD="$state_token"
}

ansible_env() {
  export ANSIBLE_CONFIG="$IAC_DIR/ansible/ansible.cfg"  # /mnt/c looks world-writable, so Ansible ignores a cwd ansible.cfg
  cd "$IAC_DIR/ansible"
  if [[ -n "$GITLAB_TOKEN_FILE" && -r "$GITLAB_TOKEN_FILE" ]]; then
    local name
    for name in $(sed -n 's/^\(GITLAB_RUNNER_TOKEN_[A-Z0-9_]*\)=.*/\1/p' "$GITLAB_TOKEN_FILE"); do
      export "$name=$(token_from_file "$name")"
    done
  fi
}

cmd=${1:-}; shift || true
case "$cmd" in
  tf)
    tf_env
    cd "$IAC_DIR/terraform/$IAC_SITE"
    exec terraform "$@"
    ;;
  inventory)
    tf_env
    # One file per site, so writing one site's inventory never drops another site's guests.
    # xmansion keeps the original name, so existing control nodes don't end up with a stale copy.
    inv="guests.yml"
    [[ "$IAC_SITE" == xmansion ]] || inv="guests-$IAC_SITE.yml"
    cd "$IAC_DIR/terraform/$IAC_SITE"
    terraform output -json guests | python3 -c '
import json, sys
guests = json.load(sys.stdin)
children = {"lxc_guests": {"hosts": {}}, "vm_guests": {"hosts": {}}}
for name, g in guests.items():
    kind = g.get("kind", "lxc")
    children[kind + "_guests"]["hosts"][name] = {"ansible_host": g["ip"], "vmid": g["vmid"], "pve_node": g["node"], "pve_tags": g["tags"]}
    for group in g["groups"]:
        children.setdefault(group, {"hosts": {}})["hosts"][name] = {}
print("# Generated by iac/scripts/iac.sh inventory from Terraform output. Do not edit.")
print(json.dumps({"all": {"children": children}}, indent=2))
' > "$IAC_DIR/ansible/inventory/$inv"
    echo "wrote ansible/inventory/$inv"
    ;;
  play)
    pb=${1:?usage: iac.sh play <playbook> [ansible-playbook args]}; shift
    ansible_env
    exec ansible-playbook "playbooks/$pb" "$@" </dev/null
    ;;
  bootstrap)
    guest=${1:?usage: iac.sh bootstrap <guest>}; shift
    ansible_env
    ip=$(ansible-inventory --host "$guest" | python3 -c 'import sys,json; print(json.load(sys.stdin)["ansible_host"])')
    # A rebuilt guest has a new host key; forget the old one before first contact.
    ssh-keygen -R "$ip" -f "$HOME/.ssh/known_hosts_iac" >/dev/null 2>&1 || true
    exec ansible-playbook playbooks/bootstrap.yml -l "$guest" "$@" </dev/null
    ;;
  *)
    sed -n '2,20p' "$0"
    exit 2
    ;;
esac
